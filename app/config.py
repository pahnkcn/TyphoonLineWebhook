"""
โมดูลการกำหนดค่าสำหรับแชทบอท 'ใจดี'
จัดการตัวแปรสภาพแวดล้อมและการตั้งค่าต่างๆ
"""
import os
import sys
import logging
from dotenv import load_dotenv
from dataclasses import dataclass, field
from typing import Optional

# โหลดตัวแปรสภาพแวดล้อม
load_dotenv()

@dataclass
class Config:
    """คลาสเก็บการตั้งค่าแอปพลิเคชัน"""
    # LINE API Credentials
    LINE_CHANNEL_ACCESS_TOKEN: str
    LINE_CHANNEL_SECRET: str
    
    # xAI Grok API Configuration
    XAI_API_KEY: str
    
    # Redis Configuration
    REDIS_HOST: str
    REDIS_PORT: int
    REDIS_DB: int
    
    # MySQL Configuration
    MYSQL_HOST: str
    MYSQL_PORT: int
    MYSQL_USER: str
    MYSQL_PASSWORD: str
    MYSQL_DB: str
    
    # Application Settings
    ENVIRONMENT: str
    LOG_LEVEL: str
    PORT: int
    
    # ตัวแปรที่มีค่าเริ่มต้นต้องมาหลังตัวแปรที่ไม่มีค่าเริ่มต้น
    XAI_MODEL: str = field(default="grok-4-1-fast-reasoning")

def load_config():
    """
    โหลดและตรวจสอบตัวแปรสภาพแวดล้อมที่จำเป็น
    
    Returns:
        Config: ออบเจ็กต์การตั้งค่าที่มีค่าตัวแปรสภาพแวดล้อม
    
    Raises:
        SystemExit: ถ้าตัวแปรสภาพแวดล้อมที่จำเป็นหายไป
    """
    # ตรวจสอบตัวแปรสภาพแวดล้อมที่จำเป็น
    required_vars = [
        'LINE_CHANNEL_ACCESS_TOKEN',
        'LINE_CHANNEL_SECRET',
        'XAI_API_KEY',
        'MYSQL_HOST',
        'MYSQL_USER',
        'MYSQL_PASSWORD',
        'MYSQL_DB'
    ]
    
    missing = [var for var in required_vars if not os.getenv(var)]
    
    if missing:
        print(f"ข้อผิดพลาด: ตัวแปรสภาพแวดล้อมที่จำเป็นหายไป: {', '.join(missing)}")
        print("กรุณาตรวจสอบไฟล์ .env หรือการตั้งค่าสภาพแวดล้อมของคุณ")
        sys.exit(1)
    
    # ตั้งค่าเริ่มต้นสำหรับตัวแปรที่เป็นตัวเลือก
    defaults = {
        'REDIS_HOST': 'localhost',
        'REDIS_PORT': '6379',
        'REDIS_DB': '0',
        'MYSQL_PORT': '3306',
        'ENVIRONMENT': 'development',
        'LOG_LEVEL': 'INFO',
        'PORT': '5000',
        'XAI_MODEL': 'grok-4-1-fast-reasoning'
    }
    
    for var, default in defaults.items():
        if not os.getenv(var):
            os.environ[var] = default
            print(f"ใช้ค่าเริ่มต้นสำหรับ {var}: {default}")
    
    # ตรวจสอบค่าตัวเลข
    numeric_vars = ['REDIS_PORT', 'REDIS_DB', 'MYSQL_PORT', 'PORT']
    for var in numeric_vars:
        try:
            int(os.getenv(var))
        except ValueError:
            print(f"ข้อผิดพลาด: {var} ต้องเป็นตัวเลข")
            sys.exit(1)
    
    # ตรวจสอบ LOG_LEVEL ที่ถูกต้อง
    valid_log_levels = {'DEBUG', 'INFO', 'WARNING', 'ERROR', 'CRITICAL'}
    log_level = os.getenv('LOG_LEVEL', 'INFO').upper()
    if log_level not in valid_log_levels:
        print(f"คำเตือน: LOG_LEVEL '{log_level}' ไม่ถูกต้อง ใช้ค่าเริ่มต้น INFO (ค่าที่รองรับ: {', '.join(sorted(valid_log_levels))})")
        os.environ['LOG_LEVEL'] = 'INFO'

    # ตรวจสอบค่า placeholder ในโหมด production
    environment = os.getenv('ENVIRONMENT', 'development')
    if environment == 'production':
        placeholder_patterns = ['your_', 'change_this', 'example', 'placeholder', 'xxx']
        sensitive_vars = {
            'LINE_CHANNEL_ACCESS_TOKEN': os.getenv('LINE_CHANNEL_ACCESS_TOKEN', ''),
            'LINE_CHANNEL_SECRET': os.getenv('LINE_CHANNEL_SECRET', ''),
            'XAI_API_KEY': os.getenv('XAI_API_KEY', ''),
            'MYSQL_PASSWORD': os.getenv('MYSQL_PASSWORD', ''),
            'DASHBOARD_API_KEY': os.getenv('DASHBOARD_API_KEY', ''),
            'FORM_WEBHOOK_KEY': os.getenv('FORM_WEBHOOK_KEY', ''),
        }
        for var_name, var_value in sensitive_vars.items():
            if any(p in var_value.lower() for p in placeholder_patterns):
                logging.critical(f"SECURITY: {var_name} ดูเหมือนค่า placeholder ในโหมด production! กรุณาตั้งค่าที่ถูกต้อง")
                sys.exit(1)

    # สร้างออบเจ็กต์การตั้งค่า
    config = Config(
        LINE_CHANNEL_ACCESS_TOKEN=os.getenv('LINE_CHANNEL_ACCESS_TOKEN'),
        LINE_CHANNEL_SECRET=os.getenv('LINE_CHANNEL_SECRET'),
        XAI_API_KEY=os.getenv('XAI_API_KEY'),
        REDIS_HOST=os.getenv('REDIS_HOST'),
        REDIS_PORT=int(os.getenv('REDIS_PORT')),
        REDIS_DB=int(os.getenv('REDIS_DB')),
        MYSQL_HOST=os.getenv('MYSQL_HOST'),
        MYSQL_PORT=int(os.getenv('MYSQL_PORT')),
        MYSQL_USER=os.getenv('MYSQL_USER'),
        MYSQL_PASSWORD=os.getenv('MYSQL_PASSWORD'),
        MYSQL_DB=os.getenv('MYSQL_DB'),
        ENVIRONMENT=environment,
        LOG_LEVEL=os.getenv('LOG_LEVEL'),
        PORT=int(os.getenv('PORT')),
        XAI_MODEL=os.getenv('XAI_MODEL', 'grok-4-1-fast-reasoning')
    )

    logging.info(f"โหลดการตั้งค่าสำเร็จ (สภาพแวดล้อม: {environment}, โมเดล: {config.XAI_MODEL})")
    return config

